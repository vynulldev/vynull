// BuildMenuRows generates the PDB menu table from a list of visible
// category IDs (in display order) and a list of hidden ones.
// `visible` entries get sort_order 1..N and visibility=0 (Visible).
// `hidden` entries get sort_order 0 and visibility=1 (Hidden).
// Hidden also includes the special category 27 (MATCHING) with visibility=3
// to match the expected layout.
func BuildMenuRows(visible []uint16, hidden []uint16) [][]byte {
	rows := make([][]byte, 0, len(visible)+len(hidden))
	make1 := func(cat uint16, vis byte, sort uint16) []byte {
		row := make([]byte, 8)
		le16put(row, 0, cat)
		le16put(row, 2, MenuCategoryContentPointer[cat])
		row[4] = MenuCategoryUnknown[cat]
		row[5] = vis
		le16put(row, 6, sort)
		return row
	}
	for _, cat := range hidden {
		vis := byte(1)
		if cat == 27 {
			vis = 3
		}
		rows = append(rows, make1(cat, vis, 0))
	}
	for i, cat := range visible {
		rows = append(rows, make1(cat, 0, uint16(i+1)))
	}
	return rows
}

