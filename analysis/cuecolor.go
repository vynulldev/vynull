// NearestCueColorID returns the palette color_id whose RGB is closest to the
// given triplet (squared-Euclidean distance; ties resolve to the lower id so the
// result is deterministic). Used when a cue carries a zero palette index but a
// real colour in its RGB bytes — the CDJ encodes its default hot-cue green that
// way, and taking index 0 alone would paint Pioneer orange (palette 0x00).
func NearestCueColorID(r, g, b byte) uint32 {
	best := uint32(0)
	bestDist := -1
	for idx, c := range CueColorPalette {
		if idx == 0 {
			continue // 0 is the unset slot, not a pickable colour
		}
		dr, dg, db := int(c[0])-int(r), int(c[1])-int(g), int(c[2])-int(b)
		d := dr*dr + dg*dg + db*db
		if bestDist < 0 || d < bestDist || (d == bestDist && idx < best) {
			bestDist, best = d, idx
		}
	}
	return best
}
